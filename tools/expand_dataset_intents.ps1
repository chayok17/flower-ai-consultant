$rows = New-Object System.Collections.Generic.List[object]
$seen = New-Object 'System.Collections.Generic.HashSet[string]'

foreach ($intent in $groups.Keys) {
  foreach ($text in $groups[$intent]) {
    $normalized = $text.Trim().ToLowerInvariant()
    if ($normalized.Length -eq 0) { continue }
    $key = "$normalized|$intent"
    if ($seen.Add($key)) {
      $rows.Add([pscustomobject]@{ text = $normalized; intent = $intent })
    }
  }
}

$rows | Export-Csv -Path $OutputPath -NoTypeInformation -Encoding UTF8

$counts = $rows | Group-Object intent | Sort-Object Name | ForEach-Object {
  [pscustomobject]@{ intent = $_.Name; count = $_.Count }
}

Write-Host "Wrote $($rows.Count) rows to $OutputPath"
$counts | Format-Table -AutoSize
